from telegram import Update
from telegram.ext import ContextTypes


async def help_menu(update: Update, context: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    await query.answer()

    text = (
        "🆘 مركز المساعدة — نظام إدارة اشتراكات قنوات VIP\n\n"
        "مرحباً بك 👋\n"
        "هذا البوت مصمّم لمساعدة أصحاب القنوات في إدارة مشتركيهم بسهولة واحترافية.\n\n"
        "طريقة الاستخدام:\n\n"
        "1️⃣ أضف البوت كـ مشرف (Admin) داخل القناة أو المجموعة مع تفعيل صلاحيات:\n"
        "• دعوة المستخدمين\n"
        "• حظر المستخدمين\n\n"
        "2️⃣ من القائمة الرئيسية اضغط (🔗 ربط قناة / مجموعة) ثم أرسل chat_id للقناة.\n\n"
        "3️⃣ ادخل إلى (👤 إدارة المشتركين) لإضافة المشتركين وتحديد مدة اشتراكهم.\n\n"
        "4️⃣ عند انتهاء الاشتراك سيقوم النظام تلقائياً بـ:\n"
        "• تحديث حالة المشترك\n"
        "• إزالة المستخدم من القناة (إذا كان الحذف التلقائي مفعّلاً)\n\n"
        "5️⃣ يمكنك تعديل مدة صلاحية روابط الدعوة وإعدادات التنبيهات ورسالة الترحيب من خلال (⚙️ إعدادات القناة).\n\n"
        "في حال واجهت أي مشكلة، تواصل مع إدارة النظام."
    )

    await query.edit_message_text(text)
